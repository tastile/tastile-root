export function costSummary(model: Model): { byEnv: Record<string, number>; maxByEnv: Record<string, number>; total: number; totalMax: number; current: number } {
  const byEnv: Record<string, number> = {};
  const maxByEnv: Record<string, number> = {};
  let current = 0;
  for (const n of model.docs.deployment.nodes as Doc[]) {
    const v = Number(n.cost_usd_month?.value ?? 0);
    const mx = Number(n.cost_usd_month?.max ?? v);
    if (n.lifecycle === "retiring") {
      current += v;
      continue;
    }
    byEnv[n.env] = (byEnv[n.env] ?? 0) + v;
    maxByEnv[n.env] = (maxByEnv[n.env] ?? 0) + mx;
  }
  const round = (x: number) => Math.round(x * 100) / 100;
  for (const k of Object.keys(byEnv)) {
    byEnv[k] = round(byEnv[k]);
    maxByEnv[k] = round(maxByEnv[k]);
  }
  const total = round(Object.values(byEnv).reduce((a, b) => a + b, 0));
  const totalMax = round(Object.values(maxByEnv).reduce((a, b) => a + b, 0));
  return { byEnv, maxByEnv, total, totalMax, current: round(current) };
}

function mdDeployment(model: Model): string {
  const d = model.docs.deployment;
  const c = costSummary(model);
  let out = `${HEADER_MD}# Deployment topology\n\n## Cost summary (USD / month, list-price estimate)\n\n`;
  out += table(
    ["scope", "expected", "upper bound"],
    [
      ...Object.keys(c.byEnv)
        .sort()
        .map((k) => [`target ${k}`, c.byEnv[k], c.maxByEnv[k]]),
      ["**target total**", c.total, c.totalMax],
      ["current (retiring nodes, unverified)", c.current, ""],
      ["budget (quality.yaml cost_budget.pre_launch)", model.docs.quality.cost_budget.target.pre_launch, ""],
    ],
  );
  out += "\n## Providers\n\n";
  out += table(["id", "name", "role", "lifecycle"], (d.providers as Doc[]).map((p) => [`\`${p.id}\``, p.name, p.role, p.lifecycle + (p.retire_by ? ` → ${p.retire_by}` : "")]));
  out += "\n## Nodes\n\n";
  out += table(
    ["id", "env", "provider", "service", "hosts", "config", "cost", "lifecycle"],
    (d.nodes as Doc[]).map((n) => [
      `\`${n.id}\``,
      n.env,
      n.provider,
      n.service,
      n.hosts,
      n.config ?? "",
      n.cost_usd_month ? `${n.cost_usd_month.value}${n.cost_usd_month.max !== undefined ? `–${n.cost_usd_month.max}` : ""} (${n.cost_usd_month.basis}) ${n.cost_usd_month.assumption ?? ""}` : "",
      n.lifecycle,
    ]),
  );
  return out;
}

