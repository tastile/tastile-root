function mdGlossary(model: Model): string {
  const g = model.docs.glossary;
  const defs = (g.terms as Doc[]).filter((t) => t.definition);
  const refs = (g.terms as Doc[]).filter((t) => t.domain_ref);
  let out = `${HEADER_MD}# System / operations glossary\n\n`;
  out += "## Defined here (mechanism layer)\n\n";
  out += table(["term", "definition", "id"], defs.map((t) => [`**${t.term}**`, t.definition, `\`${t.id}\``]));
  out += "\n## Defined by tastile-core (meaning layer) — pointers only\n\n";
  out += table(["term", "canonical definition", "id"], refs.map((t) => [t.term, t.domain_ref, `\`${t.id}\``]));
  out += "\n## Disambiguation rules\n\n";
  out += table(["words", "rule"], (g.disambiguation as Doc[]).map((d) => [d.words, d.rule]));
  out += "\n## Forbidden terms in canonical root prose\n\n";
  out += table(["pattern", "reason", "use instead"], (g.forbidden_terms as Doc[]).map((f) => [`\`${f.pattern}\``, f.reason, f.replacement]));
  return out;
}

