function mdElements(model: Model): string {
  const rows = (model.docs.elements.elements as Doc[]).map((e) => [
    `\`${e.id}\``,
    e.kind,
    e.name,
    e.parent ?? "",
    e.repository ?? "",
    e.technology ?? "",
    e.lifecycle + (e.retire_by ? ` → ${e.retire_by}` : ""),
    e.description,
  ]);
  return `${HEADER_MD}# Elements\n\n${table(["id", "kind", "name", "parent", "repo", "technology", "lifecycle", "description"], rows)}`;
}

