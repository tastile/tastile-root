// Generates derived views (D2) and markdown catalogs from the architecture model.
// Output is deterministic so validate.ts can check freshness.
//   bun scripts/architecture/generate.ts          → write architecture/views/*.d2 and architecture/generated/*.md
//   generateAll(model)                            → Map<relative path, content> (used by validate.ts)
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { type Doc, type Model, ROOT, loadModel } from "./model.ts";

const HEADER_D2 = "# GENERATED by scripts/architecture/generate.ts from architecture/model/*.yaml — do not edit.\n";
const HEADER_MD =
  "<!-- GENERATED by scripts/architecture/generate.ts from architecture/model/*.yaml — do not edit. -->\n";

const key = (id: string) => id.replace(/[.-]/g, "_");
// D2 treats `$` inside labels as a substitution start; escape it. Labels are kept single-line.
const q = (s: string) => `"${String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$").replace(/\n/g, " ")}"`;
const cell = (v: unknown) =>
  v === undefined || v === null
    ? ""
    : String(Array.isArray(v) ? v.join(", ") : typeof v === "object" ? JSON.stringify(v) : v)
        .replace(/\|/g, "\\|")
        .replace(/\n/g, " ")
        .trim();

function table(headers: string[], rows: unknown[][]): string {
  const out = [`| ${headers.join(" | ")} |`, `| ${headers.map(() => "---").join(" | ")} |`];
  for (const r of rows) out.push(`| ${r.map(cell).join(" | ")} |`);
  return `${out.join("\n")}\n`;
}

function elementsById(model: Model): Map<string, Doc> {
  return new Map((model.docs.elements.elements as Doc[]).map((e) => [e.id, e]));
}

/** Walk parents until `pred` matches. */
function ancestor(els: Map<string, Doc>, id: string, pred: (e: Doc) => boolean): Doc | undefined {
  let cur = els.get(id);
  while (cur) {
    if (pred(cur)) return cur;
    cur = cur.parent ? els.get(cur.parent) : undefined;
  }
  return undefined;
}

function styleFor(e: Doc): string[] {
  const s: string[] = [];
  if (e.kind === "person") s.push("shape: person");
  if (e.kind === "data_store") s.push("shape: cylinder");
  if (e.kind === "external_system") s.push("style.fill: \"#eeeeee\"");
  if (e.lifecycle === "planned") s.push("style.stroke-dash: 4");
  if (e.lifecycle === "retiring") s.push("style.opacity: 0.45");
  return s;
}

function node(k: string, label: string, styles: string[], indent = ""): string {
  if (styles.length === 0) return `${indent}${k}: ${q(label)}\n`;
  return `${indent}${k}: ${q(label)} {\n${styles.map((s) => `${indent}  ${s}\n`).join("")}${indent}}\n`;
}

function d2Preamble(title: string, direction = "right"): string {
  return `${HEADER_D2}vars: {\n  d2-config: {\n    layout-engine: elk\n  }\n}\ndirection: ${direction}\ntitle: ${q(title)} {\n  near: top-center\n  shape: text\n  style.font-size: 24\n}\n\n`;
}

const isTarget = (x: Doc) => x.lifecycle !== "retiring";
const labelOf = (e: Doc) => (e.technology ? `${e.name}\\n[${e.technology}]` : e.name);

function viewContext(model: Model): string {
  const els = elementsById(model);
  let out = d2Preamble("Tastile — system context (target)");
  const top = (id: string) =>
    ancestor(els, id, (e) => ["person", "software_system", "external_system"].includes(e.kind))?.id;
  const shown = new Set<string>();
  for (const e of els.values()) {
    if (!isTarget(e)) continue;
    if (["person", "software_system", "external_system"].includes(e.kind)) {
      out += node(key(e.id), e.name, styleFor(e));
      shown.add(e.id);
    }
  }
  const edges = new Map<string, string>();
  for (const r of model.docs.relationships.relationships as Doc[]) {
    if (!isTarget(r)) continue;
    const a = top(r.from);
    const b = top(r.to);
    if (!a || !b || a === b || !shown.has(a) || !shown.has(b)) continue;
    const k = `${key(a)} -> ${key(b)}`;
    if (!edges.has(k)) edges.set(k, r.description);
  }
  out += "\n";
  for (const [k, label] of [...edges.entries()].sort()) out += `${k}: ${q(label)}\n`;
  return out;
}

function viewContainers(model: Model): string {
  const els = elementsById(model);
  let out = d2Preamble("Tastile — containers (target)", "down");
  const containerOf = (id: string) =>
    ancestor(els, id, (e) => ["person", "container", "data_store", "external_system"].includes(e.kind));
  const pathOf = (e: Doc) => (e.parent === "sys.tastile" ? `outer.sys_tastile.${key(e.id)}` : `outer.${key(e.id)}`);
  out += "outer: \"\" {\n  grid-rows: 1\n  grid-gap: 40\n";
  out += "  users_and_externals: \"\" {\n    grid-columns: 1\n    grid-gap: 30\n";
  for (const e of els.values()) {
    if (!isTarget(e)) continue;
    if (e.kind === "person" || e.kind === "external_system") out += node(key(e.id), e.name, styleFor(e), "    ");
  }
  out += "  }\n";
  out += "  sys_tastile: \"Tastile\" {\n    style.fill: \"#f4f8ff\"\n";
  for (const e of els.values()) {
    if (!isTarget(e) || e.parent !== "sys.tastile") continue;
    out += node(key(e.id), labelOf(e), styleFor(e), "    ");
  }
  out += "  }\n}\n\n";
  const edges = new Map<string, string>();
  for (const r of model.docs.relationships.relationships as Doc[]) {
    if (!isTarget(r) || r.from.startsWith("repo.") || r.to.startsWith("repo.")) continue;
    const a = containerOf(r.from);
    const b = containerOf(r.to);
    if (!a || !b || a.id === b.id || !isTarget(a) || !isTarget(b)) continue;
    const k = `${pathOf(a)} -> ${pathOf(b)}`;
    const label = r.credential ? r.credential.replace(/^cred\./, "") : r.protocol.split(" ")[0];
    if (!edges.has(k)) edges.set(k, label);
  }
  for (const [k, label] of [...edges.entries()].sort()) out += `${k}: ${q(label)}\n`;
  return out;
}

function viewComponents(model: Model): string {
  const els = elementsById(model);
  let out = d2Preamble("Tastile — components of server-side containers (target)");
  const expanded = ["ctr.edge", "ctr.web", "ctr.core-api", "ctr.core-worker"];
  const pathOf = (id: string): string | undefined => {
    const e = els.get(id);
    if (!e) return undefined;
    if (e.kind === "component" && expanded.includes(e.parent)) return `${key(e.parent)}.${key(e.id)}`;
    const c = ancestor(els, id, (x) => ["person", "container", "data_store", "external_system"].includes(x.kind));
    return c ? key(c.id) : undefined;
  };
  for (const cid of expanded) {
    const c = els.get(cid);
    if (!c) continue;
    out += `${key(cid)}: ${q(labelOf(c))} {\n`;
    for (const e of els.values()) {
      if (e.parent === cid && e.kind === "component" && isTarget(e)) out += node(key(e.id), labelOf(e), styleFor(e), "  ");
    }
    out += "}\n";
  }
  const referenced = new Set<string>();
  const edges = new Map<string, string>();
  for (const r of model.docs.relationships.relationships as Doc[]) {
    if (!isTarget(r) || r.from.startsWith("repo.") || r.to.startsWith("repo.")) continue;
    const a = pathOf(r.from);
    const b = pathOf(r.to);
    if (!a || !b || a === b) continue;
    const touches = [a, b].some((p) => expanded.some((c) => p.startsWith(key(c))));
    if (!touches) continue;
    for (const p of [a, b]) if (!p.includes(".")) referenced.add(p);
    const k = `${a} -> ${b}`;
    if (!edges.has(k)) edges.set(k, r.credential ? r.credential.replace(/^cred\./, "") : r.protocol.split(" ")[0]);
  }
  for (const p of [...referenced].sort()) {
    if (expanded.map(key).includes(p)) continue;
    const e = [...els.values()].find((x) => key(x.id) === p);
    if (e) out += node(p, e.name, styleFor(e));
  }
  out += "\n";
  for (const [k, label] of [...edges.entries()].sort()) out += `${k}: ${q(label)}\n`;
  return out;
}

function viewTrustZones(model: Model): string {
  const els = elementsById(model);
  let out = d2Preamble("Tastile — trust zones and boundary credentials (target)", "down");
  const zoneOf = new Map<string, string>();
  const rendered = new Set<string>();
  out += "zone_stack: \"\" {\n  grid-rows: 1\n  grid-gap: 60\n";
  for (const z of model.docs.security.trust_zones as Doc[]) {
    out += `  ${key(z.id)}: ${q(z.name)} {\n    grid-columns: 1\n    grid-gap: 25\n`;
    for (const m of z.members as string[]) {
      zoneOf.set(m, z.id);
      const e = els.get(m);
      if (!e || e.kind === "component" || !isTarget(e)) {
        if (!e && m.startsWith("repo.")) {
          out += node(key(m), m, ["shape: document"], "      ");
          rendered.add(m);
        }
        continue;
      }
      out += node(key(m), e.name, styleFor(e), "      ");
      rendered.add(m);
    }
    out += "  }\n";
  }
  out += "}\n";
  const containerOf = (id: string) =>
    ancestor(els, id, (e) => e.kind !== "component")?.id ?? (id.startsWith("repo.") ? id : undefined);
  // One edge per (zone pair, from-element, to-element) is kept, but the credential list is aggregated
  // per zone pair so the picture stays readable.
  const pairCreds = new Map<string, Set<string>>();
  const pairNodes = new Map<string, Set<string>>();
  for (const r of model.docs.relationships.relationships as Doc[]) {
    if (!isTarget(r)) continue;
    const a = containerOf(r.from);
    const b = containerOf(r.to);
    if (!a || !b) continue;
    const za = zoneOf.get(a);
    const zb = zoneOf.get(b);
    if (!za || !zb || za === zb || !rendered.has(a) || !rendered.has(b)) continue;
    const k = `zone_stack.${key(za)}.${key(a)} -> zone_stack.${key(zb)}.${key(b)}`;
    if (!pairCreds.has(k)) pairCreds.set(k, new Set());
    pairCreds.get(k)?.add(r.credential ? r.credential.replace(/^cred\./, "") : "public");
    pairNodes.set(k, (pairNodes.get(k) ?? new Set()).add(r.id));
  }
  out += "\n";
  for (const [k, creds] of [...pairCreds.entries()].sort()) out += `${k}: ${q([...creds].sort().join(", "))}\n`;
  return out;
}

function viewDeployment(model: Model, env: string, which: "target" | "current"): string {
  const els = elementsById(model);
  const envDoc = (model.docs.environments.environments as Doc[]).find((e) => e.id === env);
  let out = d2Preamble(`Tastile — ${envDoc?.name ?? env} deployment (${which})`, "down");
  const nodes = (model.docs.deployment.nodes as Doc[]).filter(
    (n) =>
      (n.env === env || n.id.startsWith("node.shared.")) &&
      (which === "target" ? n.lifecycle !== "retiring" : n.lifecycle !== "planned"),
  );
  const providers = model.docs.deployment.providers as Doc[];
  // Unconnected containers are laid out side by side; stack providers vertically for readability.
  out += "provider_stack: \"\" {\n  grid-rows: 1\n  grid-gap: 40\n  style.opacity: 0\n";
  for (const p of providers) {
    const ns = nodes.filter((n) => n.provider === p.id);
    if (ns.length === 0) continue;
    out += `  ${key(p.id)}: ${q(p.name)} {\n    grid-columns: 1\n    grid-gap: 30\n`;
    for (const n of ns) {
      const cost = n.cost_usd_month ? `\n~$${n.cost_usd_month.value}/mo (${n.cost_usd_month.basis})` : "";
      const svc = n.service.length > 30 ? `${n.service.slice(0, 28)}…` : n.service;
      out += `    ${key(n.id)}: ${q(`${svc}${cost}`)} {\n`;
      if (n.lifecycle === "retiring") out += "      style.opacity: 0.6\n";
      for (const h of n.hosts as string[]) {
        const e = els.get(h);
        if (e) out += node(key(h), e.name, styleFor(e).filter((s) => !s.startsWith("style.opacity")), "      ");
      }
      out += "    }\n";
    }
    out += "  }\n";
  }
  out += "}\n\n";
  if (which === "target" && envDoc?.hostnames) {
    out += "hostnames: \"Public hostnames\" {\n  shape: page\n";
    out += `  label: ${q(Object.entries(envDoc.hostnames as Record<string, string>).map(([k, v]) => `${k}: ${v}`).join("\\n"))}\n}\n`;
  }
  return out;
}

function viewContract(model: Model): string {
  let out = d2Preamble("Tastile — API contract distribution");
  const els = elementsById(model);
  const rels = (model.docs.relationships.relationships as Doc[]).filter(
    (r) => r.from.startsWith("repo.") || r.to.startsWith("repo."),
  );
  const ids = new Set<string>();
  for (const r of rels) {
    ids.add(r.from);
    ids.add(r.to);
  }
  for (const id of [...ids].sort()) {
    const e = els.get(id);
    out += node(key(id), e ? e.name : `${id} (openapi.yaml, tagged)`, e ? styleFor(e) : ["shape: document"]);
  }
  out += "\n";
  for (const r of rels) out += `${key(r.from)} -> ${key(r.to)}: ${q(r.description)}${r.lifecycle === "planned" ? " {style.stroke-dash: 4}" : ""}\n`;
  return out;
}

